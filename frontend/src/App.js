function App() {
  return (
    <ThemeProvider theme={theme}>
      <CssBaseline />
      <NotificationProvider>
        <UserProvider>
          <Router>
          <div className="App">
            <Routes>
              {/* Public Routes */}
              <Route path="/" element={<LandingPage />} />
              <Route path="/login" element={<LoginPage />} />
              <Route path="/signup" element={<SignupPage />} />
              
              {/* Smart Dashboard Redirect */}
              <Route path="/dashboard" element={<DashboardRedirect />} />
              
              {/* Legacy Dashboard (fallback) */}
              <Route 
                path="/legacy-dashboard" 
                element={
                  <ProtectedRoute>
                    <DashboardPage />
                  </ProtectedRoute>
                } 
              />
              
              {/* Role-Based Dashboard Routes */}
              <Route 
                path="/admin/dashboard" 
                element={
                  <AdminRoute>
                    <AdminDashboard />
                  </AdminRoute>
                } 
              />
              
              <Route 
                path="/officer/dashboard" 
                element={
                  <LoanOfficerRoute>
                    <LoanOfficerDashboard />
                  </LoanOfficerRoute>
                } 
              />
              
              <Route 
                path="/beneficiary/dashboard" 
                element={
                  <BeneficiaryRoute>
                    <BeneficiaryDashboard />
                  </BeneficiaryRoute>
                } 
              />
              
              <Route 
                path="/manager/dashboard" 
                element={
                  <BankManagerRoute>
                    <BankManagerDashboard />
                  </BankManagerRoute>
                } 
              />
              
              {/* Additional Role-Based Routes */}
              <Route 
                path="/admin/*" 
                element={
                  <AdminRoute>
                    <AdminDashboard />
                  </AdminRoute>
                } 
              />
              
              <Route 
                path="/officer/*" 
                element={
                  <LoanOfficerRoute>
                    <LoanOfficerDashboard />
                  </LoanOfficerRoute>
                } 
              />
              
              <Route 
                path="/beneficiary/*" 
                element={
                  <BeneficiaryRoute>
                    <BeneficiaryDashboard />
                  </BeneficiaryRoute>
                } 
              />
              
              {/* Fallback Route */}
              <Route path="*" element={<DashboardRedirect />} />
            </Routes>
          </div>
        </Router>
      </UserProvider>
    </NotificationProvider>
    </ThemeProvider>
  );
}

export default App;